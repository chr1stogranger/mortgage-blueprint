#!/usr/bin/env python3
"""Generate src/data/licensedCounties.js from FHFA's conforming-loan-limit flat file.

One-off, kept for the yearly refresh (FHFA announces next year's limits in late
November). The SEO data pages (scripts/seo-data-pages.mjs) list every county in
Chris's licensed states, and the names must come from FHFA's own file, never
from memory, so the spellings match what getCountyLimits() normalizes.

Usage (openpyxl lives in the user site-packages, so use -E rather than -I, and
run it from the repo root, not from the download directory):

  mkdir -p /tmp/fhfa && curl -sSL -o /tmp/fhfa/cll.xlsx \\
    https://www.fhfa.gov/document/data/fullcountyloanlimitlist2026_hera-based_final_flat.xlsx
  python3 -E scripts/gen-licensed-counties.py /tmp/fhfa/cll.xlsx

For a new year: update the URL below and in src/data/loanLimits.js, refresh
loanLimits.js first, then rerun this. It fails (exit 1) when:
  - a state's county count differs from EXPECTED (stop and look; don't "fix" it),
  - any FHFA limit disagrees with getCountyLimits() for all four unit counts,
  - a COUNTY_LIMITS key for these states matches no county, or more than one.
"""
import datetime
import json
import os
import subprocess
import sys

import openpyxl

SOURCE_URL = "https://www.fhfa.gov/document/data/fullcountyloanlimitlist2026_hera-based_final_flat.xlsx"
EXPECTED = {"AZ": 15, "CA": 58, "CO": 64, "HI": 5, "NV": 17, "OR": 36, "TX": 254, "WA": 39}
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "data", "licensedCounties.js")

# Title-casing FHFA's uppercase names gets these wrong.
NAME_FIXES = {"Dewitt County": "DeWitt County"}


def title(name):
    words = []
    for w in name.lower().split(" "):
        w = w[:1].upper() + w[1:]
        if w.startswith("Mc") and len(w) > 2:
            w = "Mc" + w[2].upper() + w[3:]
        words.append(w)
    t = " ".join(words)
    return NAME_FIXES.get(t, t)


def main(path):
    ws = openpyxl.load_workbook(path, read_only=True).worksheets[0]
    rows = list(ws.iter_rows(values_only=True))
    header = rows[1]
    if header[2] != "County Name" or header[3] != "State":
        sys.exit(f"Unexpected header row: {header}")

    by_state = {st: [] for st in EXPECTED}
    for r in rows[2:]:
        st = r[3]
        if st not in by_state:
            continue
        fips = str(r[0]).zfill(2) + str(r[1]).zfill(3)
        by_state[st].append({"name": title(r[2].strip()), "fips": fips, "limits": [int(v) for v in r[5:9]]})

    bad = {st: (len(v), EXPECTED[st]) for st, v in by_state.items() if len(v) != EXPECTED[st]}
    if bad:
        for st, (got, want) in bad.items():
            print(f"{st}: FHFA has {got} counties, expected {want}", file=sys.stderr)
        sys.exit("County counts differ from the expected list. Stop and report; don't edit EXPECTED to match.")

    for st in by_state:
        by_state[st].sort(key=lambda c: c["name"])

    # Cross-check against loanLimits.js in Node: every county's four FHFA limits
    # must equal getCountyLimits().highBalance, and every COUNTY_LIMITS key for
    # these states must normalize to exactly one emitted county.
    check = r"""
import { getCountyLimits, normalizeCounty, COUNTY_LIMITS } from './src/data/loanLimits.js';
const data = JSON.parse(await new Promise((res) => { let s = ''; process.stdin.on('data', (d) => s += d); process.stdin.on('end', () => res(s)); }));
const errs = [];
for (const [st, list] of Object.entries(data)) {
  for (const c of list) {
    for (let u = 1; u <= 4; u++) {
      const got = getCountyLimits(st, c.name, u).highBalance;
      if (got !== c.limits[u - 1]) errs.push(`${st} ${c.name} ${u}-unit: FHFA ${c.limits[u - 1]} vs loanLimits.js ${got}`);
    }
  }
  for (const key of Object.keys(COUNTY_LIMITS).filter((k) => k.startsWith(st + '|'))) {
    const n = list.filter((c) => normalizeCounty(c.name) === key.slice(3)).length;
    if (n !== 1) errs.push(`COUNTY_LIMITS ${key} matches ${n} counties`);
  }
}
if (errs.length) { console.error(errs.join('\n')); process.exit(1); }
console.log('cross-check OK');
"""
    repo = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    res = subprocess.run(["node", "--input-type=module", "-e", check], cwd=repo,
                         input=json.dumps(by_state), text=True)
    if res.returncode != 0:
        sys.exit("Cross-check against src/data/loanLimits.js failed.")

    today = datetime.date.today().isoformat()
    lines = [
        "// GENERATED by scripts/gen-licensed-counties.py — do not hand-edit.",
        "//",
        "// Every county FHFA lists for the states Chris is licensed in, with the name",
        "// as FHFA prints it (title-cased) and the 5-digit FIPS code. Limits are NOT",
        "// here: read them through getCountyLimits() in ./loanLimits.js.",
        f"// Source: {SOURCE_URL}",
        f"// Downloaded {today}. Counts: " + ", ".join(f"{st} {n}" for st, n in EXPECTED.items())
        + f" ({sum(EXPECTED.values())} total).",
        "",
        "export const LICENSED_COUNTIES = {",
    ]
    for st, lst in by_state.items():
        lines.append(f"  {st}: [")
        for c in lst:
            lines.append(f"    {{ name: {json.dumps(c['name'])}, fips: \"{c['fips']}\" }},")
        lines.append("  ],")
    lines.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(OUT, repo)}: " + ", ".join(f"{st} {len(v)}" for st, v in by_state.items()))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
