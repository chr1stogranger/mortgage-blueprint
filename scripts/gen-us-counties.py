#!/usr/bin/env python3
"""Generate src/data/usCounties.js: every county FHFA lists, nationwide.

Companion to gen-licensed-counties.py, for the national loan-limit pages
(scripts/seo-data/model.js). Rerun both at the yearly FHFA refresh (late November).

Names: the licensed states keep gen-licensed-counties.py's title-cased FHFA
names (their page URLs already use them). Every other county takes the Census
Bureau's own name for the same FIPS code, which keeps the casing FHFA's
all-caps file loses (DeKalb, Doña Ana, Miami-Dade, Lac qui Parle).

Usage, from the repo root (openpyxl is in the user site-packages, so -E):

  python3 -E scripts/gen-us-counties.py <fhfa flat file.xlsx> <cb_2024_us_county_500k.zip>

It fails (exit 1) when FHFA and Census disagree on the FIPS codes, when the
total isn't EXPECTED_TOTAL, or when any FHFA limit disagrees with
getCountyLimits() in src/data/loanLimits.js for any unit count.
"""
import importlib.util
import json
import os
import subprocess
import sys
import tempfile

import openpyxl

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.join(HERE, "..")
OUT = os.path.join(REPO, "src", "data", "usCounties.js")
EXPECTED_TOTAL = 3235

spec = importlib.util.spec_from_file_location("gen_licensed", os.path.join(HERE, "gen-licensed-counties.py"))
gen_licensed = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gen_licensed)
LICENSED = set(gen_licensed.EXPECTED)

# Census's state names, shortened where the official form is long.
STATE_NAME_FIXES = {
    "United States Virgin Islands": "U.S. Virgin Islands",
    "Commonwealth of the Northern Mariana Islands": "Northern Mariana Islands",
}


def census_attrs(county_zip):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "attrs.json")
        subprocess.run(["npx", "--yes", "mapshaper@0.7.101", county_zip, "-o", out, "format=json"],
                       check=True, stdout=subprocess.DEVNULL)
        with open(out) as f:
            return {a["GEOID"]: a for a in json.load(f)}


def main(xlsx, county_zip):
    ws = openpyxl.load_workbook(xlsx, read_only=True).worksheets[0]
    rows = list(ws.iter_rows(values_only=True))
    if rows[1][2] != "County Name" or rows[1][3] != "State":
        sys.exit(f"Unexpected header row: {rows[1]}")
    census = census_attrs(county_zip)

    by_state, states = {}, {}
    for r in rows[2:]:
        if not r[3]:
            continue
        st = r[3]
        fips = str(r[0]).zfill(2) + str(r[1]).zfill(3)
        c = census.get(fips)
        if not c:
            sys.exit(f"{st} {r[2]} ({fips}) has no Census county with that FIPS code")
        if st in LICENSED:
            name = gen_licensed.title(r[2].strip())
        else:
            # Virginia's and Missouri's independent cities are "Alexandria city" in Census.
            name = c["NAMELSAD"][:-5] + " City" if c["NAMELSAD"].endswith(" city") else c["NAMELSAD"]
        states[st] = STATE_NAME_FIXES.get(c["STATE_NAME"], c["STATE_NAME"])
        by_state.setdefault(st, []).append({"name": name, "fips": fips, "limits": [int(v) for v in r[5:9]]})

    total = sum(len(v) for v in by_state.values())
    if total != EXPECTED_TOTAL or len(census) != EXPECTED_TOTAL:
        sys.exit(f"FHFA has {total} counties and Census {len(census)}, expected {EXPECTED_TOTAL}. Stop and look.")
    for st in by_state:
        by_state[st].sort(key=lambda c: c["name"])
        names = [c["name"] for c in by_state[st]]
        if len(set(names)) != len(names):
            sys.exit(f"{st} has two counties with the same name")

    check = r"""
import { getCountyLimits } from './src/data/loanLimits.js';
const data = JSON.parse(await new Promise((res) => { let s = ''; process.stdin.on('data', (d) => s += d); process.stdin.on('end', () => res(s)); }));
const errs = [];
for (const [st, list] of Object.entries(data)) for (const c of list) for (let u = 1; u <= 4; u++) {
  const got = getCountyLimits(st, c.name, u).highBalance;
  if (got !== c.limits[u - 1]) errs.push(`${st} ${c.name} ${u}-unit: FHFA ${c.limits[u - 1]} vs loanLimits.js ${got}`);
}
if (errs.length) { console.error(errs.join('\n')); process.exit(1); }
console.log('cross-check OK');
"""
    res = subprocess.run(["node", "--input-type=module", "-e", check], cwd=REPO, input=json.dumps(by_state), text=True)
    if res.returncode != 0:
        sys.exit("Cross-check against src/data/loanLimits.js failed.")

    order = sorted(by_state, key=lambda st: states[st])
    lines = [
        "// GENERATED by scripts/gen-us-counties.py — do not hand-edit.",
        "//",
        "// Every county (and county equivalent) FHFA lists, nationwide, with its",
        "// 5-digit FIPS code. Limits are NOT here: read them through getCountyLimits()",
        "// in ./loanLimits.js. Licensed-state names match ./licensedCounties.js;",
        "// the rest are the Census Bureau's names for the same FIPS codes.",
        f"// Source: {gen_licensed.SOURCE_URL}",
        f"// and https://www2.census.gov/geo/tiger/GENZ2024/shp/cb_2024_us_county_500k.zip ({total} counties).",
        "",
        "/** USPS code -> state, DC or territory name, in name order. */",
        "export const US_STATE_NAMES = {",
        *[f"  {st}: {json.dumps(states[st])}," for st in order],
        "};",
        "",
        "export const US_COUNTIES = {",
    ]
    for st in order:
        lines.append(f"  {st}: [")
        for c in by_state[st]:
            lines.append(f"    {{ name: {json.dumps(c['name'], ensure_ascii=False)}, fips: \"{c['fips']}\" }},")
        lines.append("  ],")
    lines.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(OUT, REPO)}: {len(by_state)} states/territories, {total} counties")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
